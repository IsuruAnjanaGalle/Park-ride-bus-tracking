#!/usr/bin/env python3
"""Generate mock/mocks.jac from docs/samples/<walker>.json.

The samples are real walker responses dumped by the contract test:
    DUMP_SAMPLES=1 jac test tests/contract_tests.jac
    python scripts/gen_mocks.py
Each walker gets mock_<walker>() returning the sample (MOCK_MODE "normal"),
the same envelope with every list emptied ("empty"), or an error envelope ("error").
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SAMPLES = ROOT / "docs" / "samples"
OUT = ROOT / "mock" / "mocks.jac"


def jac_literal(value, indent=1):
    """Render a JSON value as a Jac literal (True/False/None, double-quoted strings)."""
    pad = "    " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        if all(not isinstance(v, (dict, list)) or not v for v in value.values()):
            return "{" + ", ".join(f"{json.dumps(k)}: {jac_literal(v)}" for k, v in value.items()) + "}"
        items = [f"{pad}{json.dumps(k)}: {jac_literal(v, indent + 1)}" for k, v in value.items()]
        return "{\n" + ",\n".join(items) + "\n" + "    " * (indent - 1) + "}"
    if isinstance(value, list):
        if not value:
            return "[]"
        if all(not isinstance(v, (dict, list)) for v in value):
            return "[" + ", ".join(jac_literal(v, indent + 1) for v in value) + "]"
        items = [f"{pad}{jac_literal(v, indent + 1)}" for v in value]
        return "[\n" + ",\n".join(items) + "\n" + "    " * (indent - 1) + "]"
    if value is True:
        return "True"
    if value is False:
        return "False"
    if value is None:
        return "None"
    return json.dumps(value, ensure_ascii=False)


def emptied(value):
    """Copy of value with every list emptied (the "empty" mock mode)."""
    if isinstance(value, dict):
        return {k: emptied(v) for k, v in value.items()}
    if isinstance(value, list):
        return []
    return value


def main():
    files = sorted(SAMPLES.glob("*.json"))
    if not files:
        sys.exit("no samples: run DUMP_SAMPLES=1 jac test tests/contract_tests.jac first")
    out = [
        '"""Mock walker responses for the screens (MOCK_MODE normal / empty / error).',
        "",
        "GENERATED by scripts/gen_mocks.py from docs/samples/*.json - do not hand-edit.",
        "Every sample is a real stub response, so mocks and walkers share one shape.",
        '"""',
        "",
        'glob MOCK_MODE: str = "normal";',
        "",
        '"""Switch every mock to "normal", "empty" or "error"."""',
        "def set_mock_mode(mode: str) -> None {",
        "    MOCK_MODE = mode;",
        "}",
        "",
        "def get_mock_mode -> str {",
        "    return MOCK_MODE;",
        "}",
        "",
        '"""Copy of a value with every list emptied (MOCK_MODE "empty")."""',
        "def _emptied(value: any) -> any {",
        "    if Array.isArray(value) {",
        "        return [];",
        "    }",
        '    if value and typeof(value) == "object" {',
        "        out: dict[str, any] = {};",
        "        for k in Object.keys(value) {",
        "            out[k] = _emptied(value[k]);",
        "        }",
        "        return out;",
        "    }",
        "    return value;",
        "}",
        "",
        "def _pick(name: str, normal: dict[str, any]) -> dict[str, any] {",
        '    if MOCK_MODE == "error" {',
        '        return {"ok": False, "data": None, "error": {"code": "MOCK_ERROR", "message": "Mock error from " + name + "."}};',
        "    }",
        '    return _emptied(normal) if MOCK_MODE == "empty" else normal;',
        "}",
        "",
    ]
    for path in files:
        name = path.stem
        env = json.loads(path.read_text(encoding="utf-8"))
        out += [
            f"def mock_{name} -> dict[str, any] {{",
            f"    return _pick(\n        {json.dumps(name)},",
            f"        {jac_literal(env, 3)}",
            "    );",
            "}",
            "",
        ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} with {len(files)} mocks")


if __name__ == "__main__":
    main()
